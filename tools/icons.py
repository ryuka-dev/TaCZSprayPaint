#!/usr/bin/env python3
"""Draws the two item icons, 16x16 like vanilla's, from the letter grids below (light from the top left):

    python tools/icons.py

Writes src/main/resources/assets/taczspray/textures/item/spray_can.png and paint_remover.png, and an 8x preview of both
in build/icons-preview.png.
"""
