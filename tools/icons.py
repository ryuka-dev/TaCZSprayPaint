PALETTE = {
    ".": None,
    "k": (32, 30, 34),
    # nozzle cap
    "R": (226, 86, 74), "r": (176, 52, 46),
    # steel, light to dark
    "H": (222, 226, 230), "s": (176, 182, 190), "m": (128, 134, 144), "d": (92, 96, 106),
    # label bands, each light and dark
    "P": (238, 124, 168), "p": (204, 86, 134), "q": (160, 60, 104),
    "Y": (246, 206, 92), "y": (222, 170, 52), "z": (176, 128, 34),
    "G": (120, 196, 110), "g": (80, 160, 80), "f": (56, 120, 60),
    "B": (104, 152, 232), "b": (70, 112, 200), "n": (48, 80, 156),
    # cork
    "C": (196, 154, 104), "c": (150, 110, 70),
    # glass and solvent
    "W": (236, 246, 250), "w": (188, 214, 224), "L": (206, 236, 242), "l": (156, 206, 220), "v": (110, 164, 186),
    # label
    "T": (240, 232, 208), "t": (206, 194, 164),
}


def draw(grid):
    rows = [r for r in grid.strip("\n").split("\n")]
    if len(rows) != 16 or any(len(r) != 16 for r in rows):
        raise SystemExit("a grid must be 16 rows of 16")
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch not in PALETTE:
                raise SystemExit(f"unknown letter {ch!r}")
            if PALETTE[ch]:
                img.putpixel((x, y), PALETTE[ch] + (255,))
    return img


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    icons = {"spray_can": draw(SPRAY_CAN), "paint_remover": draw(PAINT_REMOVER)}
    preview = Image.new("RGBA", (16 * 8 * 2 + 8, 16 * 8), (139, 139, 139, 255))
    for i, (name, img) in enumerate(icons.items()):
        img.save(OUT / f"{name}.png")
        big = img.resize((128, 128), Image.NEAREST)
        preview.alpha_composite(big, (i * (128 + 8), 0))
    (ROOT / "build").mkdir(exist_ok=True)
    preview.save(ROOT / "build/icons-preview.png")
    print("icons written")


if __name__ == "__main__":
    main()
